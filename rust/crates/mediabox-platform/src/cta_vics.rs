use mediabox_core::ModeTiming;

/// The kernel's mode for a CTA-861 video code (`cea_mode_for_vic`).
pub(crate) fn cta_mode(vic: u8) -> Option<ModeTiming> {
    CTA_VICS
        .iter()
        .find(|entry| entry.0 == vic)
        .map(|&(_, clock, hd, hss, hse, ht, hsk, vd, vss, vse, vt, vs, flags)| {
            ModeTiming::new(clock, hd, hss, hse, ht, hsk, vd, vss, vse, vt, vs, flags)
        })
}

/// `KHZ2PICOS` (include/uapi/linux/fb.h): the period of a clock, in whole
/// picoseconds -- which is how the kernel lets two clocks a kilohertz apart
/// count as the same one.
fn khz_to_picos(khz: u32) -> u32 {
    if khz == 0 { 0 } else { 1_000_000_000 / khz }
}

/// `cea_mode_alternate_clock` (drivers/gpu/drm/drm_edid.c): the 1000/1001
/// variant of a CTA mode whose nominal refresh is a multiple of 6 Hz. The
/// table holds the 59.94 Hz clock for 240- and 480-line modes and the 60 Hz
/// one for the rest.
fn cea_mode_alternate_clock(mode: &ModeTiming) -> u32 {
    let clock = mode.clock_khz;
    if mode.refresh().hertz_rounded() % 6 != 0 {
        return clock;
    }
    let clock = u64::from(clock);
    let alternate = if mode.vdisplay == 240 || mode.vdisplay == 480 {
        (clock * 1001 + 500) / 1000
    } else {
        (clock * 1000 + 500) / 1001
    };
    alternate as u32
}

/// `cea_mode_alternate_timings`: for these codes the specification lets the
/// vertical front porch run a line longer, and the table holds the shortest.
fn cea_mode_alternate_timings(vic: u8, mode: &mut ModeTiming) -> bool {
    let longer = (matches!(vic, 8 | 9 | 12 | 13) && mode.vtotal < 263)
        || (matches!(vic, 23 | 24 | 27 | 28) && mode.vtotal < 314);
    if longer {
        mode.vsync_start += 1;
        mode.vsync_end += 1;
        mode.vtotal += 1;
    }
    longer
}

/// `drm_match_cea_mode` (drivers/gpu/drm/drm_edid.c), for a timing that
/// carries no picture aspect ratio: the code whose timings and flags are this
/// timing's, at the code's clock or its 1000/1001 variant.
pub(crate) fn match_cea_mode(to_match: &ModeTiming) -> Option<u8> {
    if to_match.clock_khz == 0 {
        return None;
    }
    let wanted = khz_to_picos(to_match.clock_khz);
    for &(vic, ..) in CTA_VICS {
        let Some(mut cea) = cta_mode(vic) else { continue };
        let clock1 = cea.clock_khz;
        let clock2 = cea_mode_alternate_clock(&cea);
        if wanted != khz_to_picos(clock1) && wanted != khz_to_picos(clock2) {
            continue;
        }
        loop {
            // The clock is not compared by `drm_mode_match` here: it was
            // matched above, to either variant.
            cea.clock_khz = to_match.clock_khz;
            if cea == *to_match {
                return Some(vic);
            }
            if !cea_mode_alternate_timings(vic, &mut cea) {
                break;
            }
        }
    }
    None
}
